// Generate src/format.ts from the PINNED upstream copy.
//
// Why a generator: the four salt tables Trae uses to encrypt its own auth value
// are 4 x 66 raw bytes. Transcribing them by hand is how a silent, unverifiable
// typo gets in. This reads them out of the pinned artifact, re-derives nothing,
// and writes them with provenance.
//
// Run:  node tools/extract-format.mjs
//
// The pin is located at runtime — `$DSH_HOME/trae-pin/<pkg>@<version>/`, with
// DSH_HOME defaulting to `~/.dsh` — so nothing here names a machine.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

/** The pinned upstream package the constants are read from. */
const PINNED_PACKAGE = 'dsh-connect-trae-3.4.0'
const DSH_HOME = process.env.DSH_HOME ?? path.join(os.homedir(), '.dsh')
const PINNED_DIR = path.join(DSH_HOME, 'trae-pin', PINNED_PACKAGE)
const SRC = process.env.TRAE_PINNED_INDEX ?? path.join(PINNED_DIR, 'lib', 'index.js')
const OUT = path.join(import.meta.dirname, '..', 'src', 'format.ts')

const text = fs.readFileSync(SRC, 'utf8')

function grab(re) {
  const m = re.exec(text)
  if (m === null) throw new Error(`pattern not found: ${re}`)
  return m[1]
}

function bytes(name) {
  const body = grab(new RegExp(`const ${name} = Uint8Array\\.from\\(\\[([\\s\\S]*?)\\]\\);`))
  const values = body
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
    .map((s) => Number(s))
  if (values.some((n) => !Number.isInteger(n) || n < 0 || n > 255)) throw new Error(`${name}: not byte values`)
  return values
}

const salts = { SALT_A: bytes('SALT_A'), SALT_B: bytes('SALT_B'), SALT_C: bytes('SALT_C'), SALT_D: bytes('SALT_D') }
const saltLengths = new Set(Object.values(salts).map((v) => v.length))
if (saltLengths.size !== 1) throw new Error(`salt tables disagree on length: ${[...saltLengths].join(', ')}`)
const saltLength = [...saltLengths][0]
if (saltLength === 0) throw new Error('salt tables are empty')
// xor() pairs A/B and C/D, so equal lengths are the only structural requirement.
console.log(`salt length: ${saltLength} bytes`)

const storageKey = JSON.parse(`"${grab(/const TRAE_AUTH_STORAGE_KEY = "([^"]+)"/)}"`)

const directoryRaw = grab(/const TRAE_DIRECTORY_FUNCTIONS = \{([\s\S]*?)\n\};/)
const directory = {}
for (const m of directoryRaw.matchAll(/(\w+):\s*\[([\s\S]*?)\]/g)) {
  directory[m[1]] = [...m[2].matchAll(/"([^"]+)"/g)].map((x) => x[1])
}
if (Object.keys(directory).length === 0) throw new Error('directory functions not parsed')

const fmt = (arr, name) =>
  `export const ${name} = Uint8Array.from([\n${arr.map((n, i) => `  ${n},${(i + 1) % 12 === 0 ? '\n' : ''}`).join('')}\n])\n`

const body = `/**
 * Trae on-disk/auth format constants.
 *
 * GENERATED by tools/extract-format.mjs — do not edit by hand; re-run the
 * generator instead. Source of the raw bytes (observation only):
 *   dsh-connect-trae@3.4.0 lib/index.js (MIT), pinned copy under
 *   $DSH_HOME/trae-pin/dsh-connect-trae-3.4.0/ (DSH_HOME defaults to ~/.dsh)
 *
 * These are properties of TRAE's own file format (how the desktop app encrypts
 * the value under its \`${storageKey}\` storage key), not creative code.
 */

/** Trae storage.json key holding the encrypted auth document. */
export const TRAE_AUTH_STORAGE_KEY = ${JSON.stringify(storageKey)}

${fmt(salts.SALT_A, 'SALT_A')}
${fmt(salts.SALT_B, 'SALT_B')}
${fmt(salts.SALT_C, 'SALT_C')}
${fmt(salts.SALT_D, 'SALT_D')}
/**
 * Directory functions asked on \`POST /api/ide/v1/get_detail_param\`, per region.
 *
 * Every function is asked and the answers are unioned: Trae splits its roster
 * across SOLO modes, and asking one function silently hides the models the
 * other one serves.
 */
export const TRAE_DIRECTORY_FUNCTIONS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(directory, null, 2)}
`

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, body, 'utf8')
console.log(`wrote ${OUT}`)
console.log(`  storage key : ${storageKey}`)
console.log(`  salts       : ${Object.entries(salts).map(([k, v]) => `${k}=${v.length}B`).join(' ')}`)
console.log(`  directory   : ${Object.entries(directory).map(([k, v]) => `${k}=[${v.join(',')}]`).join(' ')}`)
